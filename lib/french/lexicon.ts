/** Masculin singulier d'un adjectif connu, quelle que soit la forme reçue. */
export function adjectiveBase(form: string): string | undefined {
  const lower = form.toLowerCase();
  if (ADJECTIVES[lower]) return lower;
  return Object.keys(ADJECTIVES).find((base) => {
    const forms = ADJECTIVES[base]!;
    return forms.f === lower || forms.mp === lower || forms.fp === lower;
  });
}

